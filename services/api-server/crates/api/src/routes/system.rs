/// PATCH /api/v2/system/flags
async fn update_flag(
    flags_service: web::Data<Arc<SystemFlagsService>>,
    claims: JwtAuth,
    body: web::Json<UpdateSystemFlagRequest>,
) -> Result<HttpResponse, ApiError> {
    claims.ensure_permission("system:config")?;
    let updated = flags_service.update_flag(&body.path, body.value.clone()).await?;

    Ok(HttpResponse::Ok().json(json!({
        "success": true,
        "data": {
            "path": updated.get("path").unwrap_or(&serde_json::Value::Null),
            "value": updated.get("value").unwrap_or(&serde_json::Value::Null),
            "needs_restart": false,
        },
    })))
}

