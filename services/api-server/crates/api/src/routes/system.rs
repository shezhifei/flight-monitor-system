/// POST /api/v2/system/alert/test
async fn test_alert(
    system_ops_service: web::Data<Arc<SystemOpsService>>,
    hub: web::Data<Arc<SseHub>>,
    claims: JwtAuth,
    body: Option<web::Json<TestAlertRequest>>,
) -> Result<HttpResponse, ApiError> {
    ensure_admin(&claims)?;
    let payload = body.map(|value| value.into_inner()).unwrap_or(TestAlertRequest {
        title: Some("Flight Monitor Test Alert".to_string()),
        message: Some("This is a test alert generated by system admin.".to_string()),
        level: Some("warning".to_string()),
        channels: Some(vec!["log".to_string(), "email".to_string()]),
        recipients: Some(Vec::new()),
    });
    let title = payload.title.unwrap_or_else(|| "Flight Monitor Test Alert".to_string());
    let message = payload
        .message
        .unwrap_or_else(|| "This is a test alert generated by system admin.".to_string());
    let level = payload.level.unwrap_or_else(|| "warning".to_string());
    let channels = payload
        .channels
        .unwrap_or_else(|| vec!["log".to_string(), "email".to_string()]);
    let recipients = payload.recipients.unwrap_or_default();
    let requested_by = claims.0.sub.as_deref().unwrap_or("system_admin");
    let result = system_ops_service
        .send_test_alert(&title, &message, &level, &channels, &recipients, requested_by)
        .await?;

    let _ = hub
        .broadcast_event(
            "global_status",
            Some("system_alert"),
            json!({
                "type": "manual_test_alert",
                "title": title,
                "message": message,
                "level": level,
                "channels": channels,
                "recipients": recipients,
                "requested_by": requested_by,
                "timestamp": chrono::Utc::now().to_rfc3339(),
            }),
        )
        .await;

    Ok(HttpResponse::Ok().json(json!({
        "success": true,
        "message": "Test alert sent",
        "data": result,
    })))
}

