fn ensure_admin(claims: &JwtAuth) -> Result<(), ApiError> {
    if claims.0.is_admin.unwrap_or(false) {
        Ok(())
    } else {
        Err(ApiError::Forbidden("管理员权限不足".into()))
    }
}

fn request_id(req: &HttpRequest) -> Option<String> {
    req.headers()
        .get("x-request-id")
        .or_else(|| req.headers().get("x-trace-id"))
        .and_then(|value| value.to_str().ok())
        .map(str::trim)
        .filter(|value| !value.is_empty())
        .map(str::to_string)
}

fn actor_id(claims: &JwtAuth) -> String {
    claims
        .0
        .sub
        .as_deref()
        .or(claims.0.username.as_deref())
        .filter(|value| !value.trim().is_empty())
        .unwrap_or("system_admin")
        .to_string()
}

fn map_import_error(error: FlightImportError, preview_id: Option<&str>) -> ApiError {
    match error {
        FlightImportError::Validation(message) => ApiError::BadRequest(message),
        FlightImportError::NotFound(_) => ApiError::NotFound(match preview_id {
            Some(id) => format!("导入预览不存在: {id}"),
            None => "导入预览不存在".to_string(),
        }),
        FlightImportError::Conflict(message) => ApiError::Conflict(message),
        FlightImportError::Internal(message) => ApiError::Internal(message),
    }
}

