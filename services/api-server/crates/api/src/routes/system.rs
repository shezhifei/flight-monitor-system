/// POST /api/v2/system/flight-imports/preview
///
/// Upload size limit is enforced by the global `PayloadConfig` in `main.rs`
/// (default 20 MB). Route-level duplicate checks are removed to avoid
/// inconsistent limits.
async fn preview_flight_import(
    import_service: web::Data<Arc<FlightImportService>>,
    claims: JwtAuth,
    mut multipart: Multipart,
) -> Result<HttpResponse, ApiError> {
    ensure_admin(&claims)?;
    claims.ensure_permission("flight:manage")?;

    let mut file_name: Option<String> = None;
    let mut file_bytes = Vec::new();

    while let Some(mut field) = multipart
        .try_next()
        .await
        .map_err(|error| ApiError::BadRequest(format!("读取上传表单失败: {error}")))?
    {
        let field_name = field
            .content_disposition()
            .and_then(|disposition| disposition.get_name())
            .unwrap_or("")
            .to_string();
        if field_name != "file" {
            continue;
        }

        file_name = field
            .content_disposition()
            .and_then(|disposition| disposition.get_filename())
            .map(str::to_string)
            .or_else(|| Some("flight-import.csv".to_string()));

        while let Some(chunk) = field.next().await {
            let chunk = chunk.map_err(|error| ApiError::BadRequest(format!("读取上传文件失败: {error}")))?;
            file_bytes.extend_from_slice(&chunk);
        }
    }

    if file_bytes.is_empty() {
        return Err(ApiError::BadRequest("请上传导入文件".to_string()));
    }

    let preview = import_service
        .create_preview_from_bytes(file_name.as_deref().unwrap_or("flight-import.csv"), &file_bytes)
        .await
        .map_err(|error| map_import_error(error, None))?;
    Ok(HttpResponse::Ok().json(preview))
}

/// GET /api/v2/system/flight-imports/{preview_id}
async fn get_flight_import_preview(
    import_service: web::Data<Arc<FlightImportService>>,
    claims: JwtAuth,
    path: web::Path<String>,
) -> Result<HttpResponse, ApiError> {
    ensure_admin(&claims)?;
    claims.ensure_permission("flight:manage")?;
    let preview_id = path.into_inner();
    let preview = import_service
        .get_preview(&preview_id)
        .map_err(|error| map_import_error(error, Some(&preview_id)))?;
    Ok(HttpResponse::Ok().json(preview))
}

/// POST /api/v2/system/flight-imports/{preview_id}/commit
async fn commit_flight_import(
    req: HttpRequest,
    import_service: web::Data<Arc<FlightImportService>>,
    claims: JwtAuth,
    path: web::Path<String>,
) -> Result<HttpResponse, ApiError> {
    ensure_admin(&claims)?;
    claims.ensure_permission("flight:manage")?;
    let preview_id = path.into_inner();
    let result = import_service
        .commit_preview(&preview_id, &actor_id(&claims), request_id(&req))
        .await
        .map_err(|error| map_import_error(error, Some(&preview_id)))?;
    Ok(HttpResponse::Ok().json(result))
}

/// GET /api/v2/system/flight-imports/{preview_id}/result
async fn get_flight_import_result(
    import_service: web::Data<Arc<FlightImportService>>,
    claims: JwtAuth,
    path: web::Path<String>,
) -> Result<HttpResponse, ApiError> {
    ensure_admin(&claims)?;
    claims.ensure_permission("flight:manage")?;
    let preview_id = path.into_inner();
    let result = import_service.get_result(&preview_id).map_err(|error| match error {
        FlightImportError::NotFound(_) => ApiError::NotFound(format!("导入结果不存在: {preview_id}")),
        FlightImportError::Validation(message) => ApiError::BadRequest(message),
        FlightImportError::Conflict(message) => ApiError::Conflict(message),
        FlightImportError::Internal(message) => ApiError::Internal(message),
    })?;
    Ok(HttpResponse::Ok().json(result))
}

/// 注册系统路由
pub fn configure(cfg: &mut web::ServiceConfig) {
    cfg.service(
        web::scope("/api/v2/system")
            .route("/health", web::get().to(system_health))
            .route("/airport-context", web::get().to(airport_context))
            .route(
                "/online-status/service-status",
                web::get().to(online_status_service_status),
            )
            .route("/alert/test", web::post().to(test_alert))
            .route("/flight-imports/preview", web::post().to(preview_flight_import))
            .route("/flight-imports/{preview_id}", web::get().to(get_flight_import_preview))
            .route(
                "/flight-imports/{preview_id}/commit",
                web::post().to(commit_flight_import),
            )
            .route(
                "/flight-imports/{preview_id}/result",
                web::get().to(get_flight_import_result),
            )
            .route("/flags", web::get().to(get_flags))
            .route("/flags", web::patch().to(update_flag))
            .route("/flags/export", web::get().to(export_flags)),
    );
}
